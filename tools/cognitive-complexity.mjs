import { execFile } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execute = promisify(execFile);
const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reportDirectory = path.join(repositoryRoot, ".context");
const markdownReportPath = path.join(reportDirectory, "cognitive-complexity.md");
const jsonReportPath = path.join(reportDirectory, "cognitive-complexity.json");
const sourceRoots = ["apps/desktop/src/main", "packages"];
const comparisonBase = process.env.CINESIM_COMPLEXITY_BASE ?? "origin/main";
const ruleCode = "sonarjs(cognitive-complexity)";
const controlFlowNames = new Set(["async", "catch", "for", "if", "switch", "while"]);

function extractScore(message) {
  const match = /Cognitive Complexity from (\d+) to/.exec(message);
  if (!match) {
    throw new Error(`Could not extract a cognitive-complexity score from: ${message}`);
  }

  return Number.parseInt(match[1], 10);
}

function findEnclosingFunction(lines, diagnosticLine) {
  for (let index = diagnosticLine - 1; index >= 0; index -= 1) {
    const line = lines[index];
    const declaration = /\bfunction\s+([#$A-Z_a-z][\w$#]*)/.exec(line);
    const assignment = /\b(?:const|let|var)\s+([A-Z_a-z][\w$]*)\s*=/.exec(line);
    const method =
      /^\s*(?:(?:public|private|protected|static|override|abstract|readonly)\s+)*(?:async\s+)?(?:get\s+|set\s+)?([#$A-Z_a-z][\w$#]*)\s*(?:<[^>]+>)?\s*\(/.exec(
        line,
      );
    const name = declaration?.[1] ?? assignment?.[1] ?? method?.[1];

    if (name && !controlFlowNames.has(name)) {
      return name;
    }
  }

  return undefined;
}

function identifyFunction(source, diagnostic) {
  const label = diagnostic.labels?.[0];
  const span = label?.span;
  const line = span?.line ?? 1;
  const column = span?.column ?? 1;
  const length = span?.length ?? 0;
  const lines = source.split("\n");
  const diagnosticSourceLine = lines[line - 1] ?? "";
  const token = diagnosticSourceLine.slice(column - 1, column - 1 + length).trim();

  if (/^#?[A-Z_a-z][\w$#]*$/.test(token)) {
    return token;
  }

  const linePrefix = diagnosticSourceLine.slice(0, column - 1);
  const callNames = [...linePrefix.matchAll(/([#$A-Z_a-z][\w$#]*)\s*\(/g)]
    .map((match) => match[1])
    .filter((name) => !controlFlowNames.has(name));
  const callbackOwner = callNames.at(-1);
  if (callbackOwner) {
    return `${callbackOwner} callback`;
  }

  const owner = findEnclosingFunction(lines, line);
  if (owner) {
    return `${owner} callback`;
  }

  return `anonymous callback at line ${line}`;
}

function scoreBand(score) {
  if (score > 15) {
    return "over hard ceiling";
  }
  if (score >= 11) {
    return "review required";
  }
  if (score >= 6) {
    return "helper range";
  }
  return "orchestration range";
}

function markdownLink(entry) {
  const relativePath = path.relative(reportDirectory, path.join(repositoryRoot, entry.file));
  return `[${entry.file}:${entry.line}](${relativePath}#L${entry.line})`;
}

function table(entries) {
  if (entries.length === 0) {
    return "None.";
  }

  return [
    "| Score | Function | Location | Band |",
    "| ---: | --- | --- | --- |",
    ...entries.map(
      (entry) =>
        `| ${entry.score} | \`${entry.functionName}\` | ${markdownLink(entry)} | ${scoreBand(entry.score)} |`,
    ),
  ].join("\n");
}

function count(entries, predicate) {
  return entries.filter(predicate).length;
}

function fileTable(files) {
  if (files.length === 0) return "None.";
  return [
    "| Lines | File |",
    "| ---: | --- |",
    ...files.map((file) => `| ${file.lines} | \`${file.file}\` |`),
  ].join("\n");
}

function summaryTable(entries) {
  const maximum = entries.at(0)?.score ?? 0;
  return `| Measure | Count |
| --- | ---: |
| Functions with nonzero complexity | ${entries.length} |
| Above hard ceiling (>15) | ${count(entries, (entry) => entry.score > 15)} |
| Review band (11–15) | ${count(entries, (entry) => entry.score >= 11 && entry.score <= 15)} |
| Helper range (6–10) | ${count(entries, (entry) => entry.score >= 6 && entry.score <= 10)} |
| Orchestration range (1–5) | ${count(entries, (entry) => entry.score >= 1 && entry.score <= 5)} |
| Maximum score | ${maximum} |`;
}

function buildMarkdown(entries, changedFiles, metadata) {
  const branchEntries = entries.filter((entry) => changedFiles.has(entry.file));
  const branchHotspots = branchEntries.filter((entry) => entry.score >= 11);
  const allHotspots = entries.filter((entry) => entry.score >= 11);
  const maximum = entries.at(0)?.score ?? 0;

  return `# Source cognitive complexity

Generated by \`vp run complexity:report\` on ${metadata.generatedAt} from commit \`${metadata.commit}\` using \`eslint-plugin-sonarjs@${metadata.analyzerVersion}\` (rule S3776).

Scope: ${sourceRoots.map((root) => `\`${root}/**/*.{ts,tsx}\``).join(" and ")}. The branch-focused sections include files changed from \`${metadata.comparisonBase}\`. The analyzer is configured with a reporting threshold of zero so every function with a nonzero score appears here. This is a local working report and intentionally lives under the gitignored \`.context/\` directory.

## Refactoring contract

- Hard ceiling: **15**. No function may remain above 15 after it is refactored.
- Review band: **11–15**. These functions need an explicit readability review when touched.
- Helper target: **10 or less**.
- Top-level orchestration target: **5 or less**. This role is assigned by a human during refactoring; the analyzer cannot infer architecture.
- Ratchet: an edited function's score must not increase, even when it already passes its target.

Scores are guardrails, not the goal. A change still needs to read naturally from top to bottom; extracting meaningless one-line wrappers just to lower a number does not satisfy the contract.

## Branch summary

${summaryTable(branchEntries)}

## Branch hotspots requiring attention

${table(branchHotspots)}

## Large changed source files

${fileTable(metadata.changedSourceFiles)}

## Full-scope summary

${summaryTable(entries)}

The full scope currently has a maximum score of ${maximum}; unchanged findings are baseline context, not part of the branch cleanup contract.

## Full-scope hotspots

${table(allHotspots)}

## Complete measured inventory

${table(entries)}
`;
}

async function analyzerVersion() {
  const packageJsonPath = path.join(
    repositoryRoot,
    "node_modules/eslint-plugin-sonarjs/package.json",
  );
  const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
  return packageJson.version;
}

async function currentCommit() {
  const { stdout } = await execute("git", ["rev-parse", "--short", "HEAD"], {
    cwd: repositoryRoot,
  });
  return stdout.trim();
}

async function changedSourceFiles() {
  const commands = [
    ["diff", "--name-only", `${comparisonBase}...HEAD`, "--", ...sourceRoots],
    ["diff", "--name-only", "--", ...sourceRoots],
    ["ls-files", "--others", "--exclude-standard", "--", ...sourceRoots],
  ];
  const outputs = await Promise.all(
    commands.map((arguments_) => execute("git", arguments_, { cwd: repositoryRoot })),
  );
  const files = [
    ...new Set(
      outputs.flatMap(({ stdout }) => stdout.trim().split("\n")).filter((file) => file.length > 0),
    ),
  ].filter((file) => /\.[cm]?[jt]sx?$/u.test(file));
  const details = await Promise.all(
    files.map(async (file) => {
      const source = await readFile(path.join(repositoryRoot, file), "utf8");
      return { file, lines: source.split("\n").length - 1 };
    }),
  );
  return details.sort(
    (left, right) => right.lines - left.lines || left.file.localeCompare(right.file),
  );
}

async function runAnalyzer() {
  const arguments_ = ["lint", ...sourceRoots, "--format", "json", "--max-warnings", "9999"];
  const options = {
    cwd: repositoryRoot,
    env: {
      ...process.env,
      CINESIM_COGNITIVE_COMPLEXITY_REPORT: "1",
    },
    maxBuffer: 16 * 1024 * 1024,
  };
  try {
    const { stdout } = await execute("vp", arguments_, options);
    return JSON.parse(stdout);
  } catch (error) {
    if (
      typeof error === "object" &&
      error !== null &&
      "stdout" in error &&
      typeof error.stdout === "string"
    ) {
      return JSON.parse(error.stdout);
    }
    throw error;
  }
}

async function main() {
  const result = await runAnalyzer();
  const changedSourceFileDetails = await changedSourceFiles();
  const changedFiles = new Set(changedSourceFileDetails.map((file) => file.file));
  const unexpectedErrors = result.diagnostics.filter(
    (diagnostic) => diagnostic.code !== ruleCode && diagnostic.severity === "error",
  );

  if (unexpectedErrors.length > 0) {
    throw new Error(
      `The lint run returned ${unexpectedErrors.length} unrelated error(s); run vp lint for details.`,
    );
  }

  const cognitiveDiagnostics = result.diagnostics.filter(
    (diagnostic) => diagnostic.code === ruleCode,
  );
  const sourceFiles = new Map();
  const entries = [];

  for (const diagnostic of cognitiveDiagnostics) {
    let source = sourceFiles.get(diagnostic.filename);
    if (!source) {
      source = await readFile(path.join(repositoryRoot, diagnostic.filename), "utf8");
      sourceFiles.set(diagnostic.filename, source);
    }

    const span = diagnostic.labels?.[0]?.span;
    entries.push({
      file: diagnostic.filename,
      functionName: identifyFunction(source, diagnostic),
      line: span?.line ?? 1,
      column: span?.column ?? 1,
      score: extractScore(diagnostic.message),
    });
  }

  entries.sort(
    (left, right) =>
      right.score - left.score || left.file.localeCompare(right.file) || left.line - right.line,
  );

  const metadata = {
    analyzerVersion: await analyzerVersion(),
    commit: await currentCommit(),
    comparisonBase,
    generatedAt: new Date().toISOString(),
    scope: sourceRoots.map((root) => `${root}/**/*.{ts,tsx}`),
    changedSourceFiles: changedSourceFileDetails,
    thresholds: {
      hardCeiling: 15,
      helperTarget: 10,
      orchestrationTarget: 5,
      reviewMinimum: 11,
    },
  };
  const jsonReport = `${JSON.stringify({ metadata, entries }, undefined, 2)}\n`;

  await mkdir(reportDirectory, { recursive: true });
  await Promise.all([
    writeFile(jsonReportPath, jsonReport),
    writeFile(markdownReportPath, buildMarkdown(entries, changedFiles, metadata)),
  ]);

  const branchEntries = entries.filter((entry) => changedFiles.has(entry.file));
  const aboveCeiling = count(branchEntries, (entry) => entry.score > 15);
  const reviewBand = count(branchEntries, (entry) => entry.score >= 11 && entry.score <= 15);
  const maximum = branchEntries.at(0)?.score ?? 0;

  process.stdout.write(
    [
      `Measured ${entries.length} functions across desktop main and package sources.`,
      `Branch focus: ${branchEntries.length} nonzero functions; ${aboveCeiling} above 15; ${reviewBand} in the 11-15 review band; maximum ${maximum}.`,
      `Markdown: ${path.relative(repositoryRoot, markdownReportPath)}`,
      `JSON: ${path.relative(repositoryRoot, jsonReportPath)}`,
      "",
    ].join("\n"),
  );
}

await main();
